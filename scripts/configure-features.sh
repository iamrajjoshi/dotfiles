#!/bin/bash
set -euo pipefail

DOTFILES_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
FEATURE_DIR="$HOME/.config/dotfiles"
STATE_FILE="$FEATURE_DIR/features.conf"
MARKER='# Generated by dotfiles configure-features.sh'

usage() {
    cat <<'HELP'
Usage: ./scripts/configure-features.sh [--tmux|--no-tmux] [--willow|--no-willow] [--shell /absolute/path]

Configure Ghostty and tmux without reinstalling dotfiles or app preferences.
New machines default to tmux enabled and Willow disabled. Later runs reuse
~/.config/dotfiles/features.conf, with command-line flags taking precedence.
The shell defaults to your account's login shell. --shell controls the shell
used by Ghostty and tmux; it does not change the account's login shell.
Dependencies must already be installed; no packages are installed here.
HELP
}

for arg in "$@"; do
    if [[ "$arg" == --help || "$arg" == -h ]]; then usage; exit 0; fi
done

USE_TMUX=1
USE_WILLOW=0
SHELL_PATH="${SHELL:-/bin/zsh}"
if command -v dscl >/dev/null 2>&1; then
    login_shell="$(dscl . -read "/Users/$(id -un)" UserShell 2>/dev/null | awk '/^UserShell: / {print $2}')" || true
    [[ -z "$login_shell" ]] || SHELL_PATH="$login_shell"
fi
# This is a user-owned shell configuration written by this script.
[[ ! -f "$STATE_FILE" ]] || source "$STATE_FILE"

while [[ $# -gt 0 ]]; do
    case "$1" in
        --tmux) USE_TMUX=1 ;;
        --no-tmux) USE_TMUX=0 ;;
        --willow) USE_WILLOW=1 ;;
        --no-willow) USE_WILLOW=0 ;;
        --shell)
            [[ $# -ge 2 ]] || { echo '--shell requires an absolute executable path' >&2; exit 2; }
            SHELL_PATH="$2"; shift ;;
        *) echo "Unknown option: $1" >&2; usage >&2; exit 2 ;;
    esac
    shift
done

[[ "$USE_TMUX" == 0 || "$USE_TMUX" == 1 ]] || { echo 'Invalid USE_TMUX in features.conf' >&2; exit 2; }
[[ "$USE_WILLOW" == 0 || "$USE_WILLOW" == 1 ]] || { echo 'Invalid USE_WILLOW in features.conf' >&2; exit 2; }
[[ "$SHELL_PATH" == /* && -x "$SHELL_PATH" && ! -d "$SHELL_PATH" ]] || { echo "Shell is not an absolute executable: $SHELL_PATH" >&2; exit 2; }
if [[ "$USE_TMUX" == 1 ]]; then
    TMUX_BIN="$(command -v tmux)" || { echo 'tmux is enabled but missing. Run ./install.sh to install dependencies' >&2; exit 1; }
fi
if [[ "$USE_WILLOW" == 1 ]]; then
    command -v willow >/dev/null 2>&1 || { echo 'Willow is enabled but missing. Install the Willow CLI before enabling it' >&2; exit 1; }
fi

# Replace links as links, never write through them into the source repository.
# Preserve the first unmanaged configuration without overwriting older backups.
write_config() {
    local dest="$1" tmp backup suffix=0
    mkdir -p "$(dirname "$dest")"
    tmp="$(mktemp "${dest}.tmp.XXXXXX")"
    cat > "$tmp"
    if [[ -f "$dest" ]] && cmp -s "$tmp" "$dest"; then rm "$tmp"; return; fi
    if [[ -e "$dest" || -L "$dest" ]]; then
        if [[ -L "$dest" || "$(head -n 1 "$dest")" != "$MARKER" ]]; then
            backup="${dest}.before-features"
            while [[ -e "$backup" || -L "$backup" ]]; do
                suffix=$((suffix + 1)); backup="${dest}.before-features.${suffix}"
            done
            mv "$dest" "$backup"
            echo "Preserved $backup"
        fi
    fi
    mv -f "$tmp" "$dest"
}

# Quote paths for tmux's configuration parser.
tmux_quote() { local value="${1//\\/\\\\}"; printf '"%s"' "${value//\"/\\\"}"; }

{
    echo "$MARKER"
    printf 'USE_TMUX=%s\nUSE_WILLOW=%s\n' "$USE_TMUX" "$USE_WILLOW"
    printf 'SHELL_PATH=%q\n' "$SHELL_PATH"
} | write_config "$STATE_FILE"

{
    echo "$MARKER"
    printf 'config-file = %s/ghostty/config\n' "$DOTFILES_DIR"
    if [[ "$USE_TMUX" == 1 ]]; then
        printf 'config-file = %s/ghostty/tmux.conf\n' "$DOTFILES_DIR"
        printf 'command = '; tmux_quote "$TMUX_BIN"; printf ' new-session -A -s main\n'
    else
        printf 'command = '; tmux_quote "$SHELL_PATH"; printf '\n'
    fi
} | write_config "$HOME/.config/ghostty/config"

{
    echo "$MARKER"
    if [[ "$USE_TMUX" == 1 ]]; then
        printf 'source-file '; tmux_quote "$DOTFILES_DIR/tmux/tmux.conf"; printf '\n'
    fi
    printf 'set -g default-shell '; tmux_quote "$SHELL_PATH"; printf '\n'
    if [[ "$USE_TMUX" == 1 ]]; then
        # Clear the old optional binding when reloading a running server.
        printf 'unbind -q w\n'
        if [[ "$USE_WILLOW" == 1 ]]; then
            printf 'source-file '; tmux_quote "$DOTFILES_DIR/tmux/willow.conf"; printf '\n'
        fi
    fi
} | write_config "$HOME/.tmux.conf"

printf 'Configured: tmux=%s willow=%s shell=%s\n' "$USE_TMUX" "$USE_WILLOW" "$SHELL_PATH"
printf 'Open a new Ghostty window to use the configuration. Existing sessions are left running.\n'
